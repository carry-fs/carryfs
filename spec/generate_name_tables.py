#!/usr/bin/env python3
"""Generate the frozen Rust filename tables from Unicode 16.0.0 sources."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
UNICODE = ROOT / "testdata" / "unicode" / "16.0.0"
OUTPUT = ROOT / "src" / "name_tables.rs"


def parse_unicode_data():
    category = {}
    combining_class = {}
    decomposition = {}
    range_start = None

    for line in (UNICODE / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        code_point = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            range_start = code_point
            continue
        if fields[1].endswith(", Last>"):
            if range_start is None:
                raise ValueError("Unicode range lacks start")
            for member in range(range_start, code_point + 1):
                category[member] = fields[2]
            range_start = None
            continue

        category[code_point] = fields[2]
        if int(fields[3]):
            combining_class[code_point] = int(fields[3])
        if fields[5] and not fields[5].startswith("<"):
            decomposition[code_point] = tuple(int(value, 16) for value in fields[5].split())

    if range_start is not None:
        raise ValueError("Unicode range lacks end")
    return category, combining_class, decomposition


def parse_exclusions():
    exclusions = set()
    for line in (UNICODE / "CompositionExclusions.txt").read_text(encoding="utf-8").splitlines():
        text = line.split("#", 1)[0].strip()
        if text:
            exclusions.add(int(text, 16))
    return exclusions


def parse_case_folding():
    folded = {}
    for line in (UNICODE / "CaseFolding.txt").read_text(encoding="utf-8").splitlines():
        text = line.split("#", 1)[0].strip()
        if text:
            code_point, status, mapping, _ = (value.strip() for value in text.split(";"))
            if status in ("C", "F"):
                folded[int(code_point, 16)] = tuple(int(value, 16) for value in mapping.split())
    return folded


def invalid_ranges(category):
    ranges = []
    start = None
    for code_point in range(0x11_0000):
        invalid = category.get(code_point, "Cn") in ("Cn", "Cs", "Cc")
        if invalid and start is None:
            start = code_point
        elif not invalid and start is not None:
            ranges.append((start, code_point - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10_FFFF))
    return ranges


def code_point(value):
    return f"0x{value:06X}"


def emit_ranges(values):
    return "\n".join(f"    ({code_point(start)}, {code_point(end)})," for start, end in values)


def emit_pairs(values):
    lines = []
    for code, mapping in values:
        members = ", ".join(code_point(value) for value in mapping)
        lines.append(f"    ({code_point(code)}, &[{members}]),")
    return "\n".join(lines)


def emit_combining(values):
    return "\n".join(
        f"    ({code_point(code)}, {class_value})," for code, class_value in values
    )


def emit_compositions(values):
    return "\n".join(
        f"    ({code_point(first)}, {code_point(second)}, {code_point(composed)}),"
        for (first, second), composed in values
    )


def generate():
    category, combining_class, decomposition = parse_unicode_data()
    exclusions = parse_exclusions()
    folded = parse_case_folding()
    compositions = {
        pair: composed
        for composed, pair in decomposition.items()
        if len(pair) == 2
        and composed not in exclusions
        and combining_class.get(pair[0], 0) == 0
    }

    output = f'''// Generated by spec/generate_name_tables.py from pinned Unicode 16.0.0 sources.
// Do not edit by hand; regenerate after an intentional filename-profile update.

pub(crate) const INVALID_CODE_POINT_RANGES: &[(u32, u32)] = &[
{emit_ranges(invalid_ranges(category))}
];

pub(crate) const COMBINING_CLASSES: &[(u32, u8)] = &[
{emit_combining(sorted(combining_class.items()))}
];

pub(crate) const CANONICAL_DECOMPOSITIONS: &[(u32, &[u32])] = &[
{emit_pairs(sorted(decomposition.items()))}
];

pub(crate) const COMPOSITIONS: &[(u32, u32, u32)] = &[
{emit_compositions(sorted(compositions.items()))}
];

pub(crate) const CASE_FOLDINGS: &[(u32, &[u32])] = &[
{emit_pairs(sorted(folded.items()))}
];
'''
    OUTPUT.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    generate()
